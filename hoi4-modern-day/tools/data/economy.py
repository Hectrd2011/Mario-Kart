def factories(tag):
    e = ECON[tag]
    civ = max(1, round(e["gdp"] / 200))
    mil = round(e["milex"] / 15) + MIL_INDUSTRY_BONUS.get(tag, 0)
    if e["milex"] >= 0.8 and mil == 0:
        mil = 1
    return civ, mil, e["docks"]


